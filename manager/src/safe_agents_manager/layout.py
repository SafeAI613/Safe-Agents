"""Paths inside one installed agent version and the generated ``langgraph.json``."""

from __future__ import annotations

import json
import os
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from .manifest import AgentManifest

# Environment variable that carries the per-launch token into the agent server.
AGENT_TOKEN_ENV = "SAFE_AGENTS_AGENT_TOKEN"
AGENT_TOKEN_HEADER = "x-api-key"

# Without this module any process or web page on the machine could call the agent server
# (CORS alone does not stop "simple" cross-site requests). It is regenerated on every start.
PLATFORM_AUTH_SOURCE = f'''"""Generated by Safe-Agents; rewritten whenever the agent starts."""

import hmac
import os

from langgraph_sdk import Auth

auth = Auth()
_TOKEN = os.environ["{AGENT_TOKEN_ENV}"].encode()


@auth.authenticate
async def authenticate(headers: dict) -> str:
    supplied = headers.get(b"{AGENT_TOKEN_HEADER}", b"")
    if not _TOKEN or not hmac.compare_digest(supplied, _TOKEN):
        raise Auth.exceptions.HTTPException(status_code=401, detail="invalid agent token")
    return "desktop-user"
'''


@dataclass(frozen=True)
class AgentLayout:
    """``agents/<agent_id>/<version>/`` with ``src/``, ``.venv/``, ``inbox/`` and the config."""

    root: Path

    @property
    def src(self) -> Path:
        return self.root / "src"

    @property
    def venv(self) -> Path:
        return self.root / ".venv"

    @property
    def inbox(self) -> Path:
        return self.root / "inbox"

    @property
    def state_dir(self) -> Path:
        """Server state (conversations); langgraph dev keeps it in its working folder."""
        return self.root / ".langgraph_api"

    @property
    def langgraph_config(self) -> Path:
        return self.root / "langgraph.json"

    @property
    def platform_auth(self) -> Path:
        return self.root / "platform_auth.py"

    @property
    def platform_launcher(self) -> Path:
        return self.root / "platform_launcher.py"

    def venv_executable(self, name: str) -> Path:
        if os.name == "nt":
            return self.venv / "Scripts" / f"{name}.exe"
        return self.venv / "bin" / name


# Runs `langgraph dev` and turns "shutdown" (or stdin closing, e.g. when the manager dies)
# into the server's own graceful shutdown, so it saves its state. This works the same on
# Windows, where console signals cannot reach a process without a console.
PLATFORM_LAUNCHER_SOURCE = '''"""Generated by Safe-Agents; rewritten whenever the agent starts."""

import signal
import sys
import threading


def _watch_stdin() -> None:
    try:
        for line in sys.stdin:
            if line.strip() == "shutdown":
                break
    except (OSError, ValueError):
        pass
    signal.raise_signal(signal.SIGINT)  # uvicorn handles it: graceful stop, state flushed


threading.Thread(target=_watch_stdin, name="platform-stdin", daemon=True).start()

from langgraph_cli.cli import cli  # noqa: E402

sys.argv[0] = "langgraph"
sys.exit(cli())
'''


def build_langgraph_config(manifest: AgentManifest) -> dict[str, Any]:
    # Secrets are injected as process environment variables, never written to disk.
    return {
        "dependencies": ["./src"],
        "graphs": {manifest.graph_id: f"./src/{manifest.graph_entry}"},
        "env": {},
        "auth": {"path": "./platform_auth.py:auth"},
    }


def write_langgraph_config(layout: AgentLayout, manifest: AgentManifest) -> Path:
    layout.platform_auth.write_text(PLATFORM_AUTH_SOURCE, encoding="utf-8")
    layout.platform_launcher.write_text(PLATFORM_LAUNCHER_SOURCE, encoding="utf-8")
    path = layout.langgraph_config
    path.write_text(json.dumps(build_langgraph_config(manifest), indent=2), encoding="utf-8")
    return path
